  // Fade in scroll
  const obs = new IntersectionObserver(entries => {
    entries.forEach(e => { if(e.isIntersecting){ e.target.classList.add('on'); obs.unobserve(e.target); }});
  }, { threshold: 0.08 });
  document.querySelectorAll('.fi').forEach(el => obs.observe(el));

  // Compteur animé
  function animateCounter(el) {
    const target = parseFloat(el.dataset.target);
    const suffix = el.dataset.suffix || '';
    const isDecimal = !Number.isInteger(target);
    const duration = 1800, steps = 60;
    let step = 0;
    const timer = setInterval(() => {
      step++;
      const current = (target / steps) * step;
      if (step >= steps) { el.textContent = (isDecimal ? target.toFixed(1) : target) + suffix; clearInterval(timer); return; }
      el.textContent = (isDecimal ? current.toFixed(1) : Math.floor(current)) + suffix;
    }, duration / steps);
  }

  const chiffresObs = new IntersectionObserver(entries => {
    entries.forEach(e => {
      if (e.isIntersecting) {
        document.querySelectorAll('.chiffre-num').forEach(animateCounter);
        chiffresObs.disconnect();
      }
    });
  }, { threshold: 0.3 });
  const chiffresSection = document.querySelector('.chiffres-bg');
  if (chiffresSection) chiffresObs.observe(chiffresSection);
</script>
